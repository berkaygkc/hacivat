// Raw read files

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct RawFile {
    format: String,
    id: String,
    engine: String,
    line: String,
    server_version: String,
    reader: String,
    sections: BTreeMap<String, RawTable>,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct RawTable {
    columns: Vec<String>,
    rows: Vec<Vec<Option<String>>>,
}

/// One raw row by column name.
struct Rec<'a> {
    section: &'a str,
    cols: &'a [String],
    row: &'a [Option<String>],
}

impl<'a> Rec<'a> {
    fn opt(&self, col: &str) -> Result<Option<&'a str>> {
        let i = self
            .cols
            .iter()
            .position(|c| c.eq_ignore_ascii_case(col))
            .with_context(|| format!("section {}: no column {col:?}", self.section))?;
        Ok(self.row.get(i).and_then(|v| v.as_deref()))
    }

    fn req(&self, col: &str) -> Result<&'a str> {
        self.opt(col)?
            .with_context(|| format!("section {}: {col} is NULL", self.section))
    }

    fn string(&self, col: &str) -> Result<String> {
        self.req(col).map(str::to_string)
    }

    fn opt_string(&self, col: &str) -> Result<Option<String>> {
        Ok(self.opt(col)?.map(str::to_string))
    }
}

impl RawFile {
    fn records(&self, section: &str) -> Result<Vec<Rec<'_>>> {
        let (name, table) = self
            .sections
            .get_key_value(section)
            .with_context(|| format!("{}: no section {section:?}", self.id))?;
        for (i, row) in table.rows.iter().enumerate() {
            ensure!(
                row.len() == table.columns.len(),
                "{}: {section} row {i} has {} values for {} columns",
                self.id,
                row.len(),
                table.columns.len()
            );
        }
        Ok(table
            .rows
            .iter()
            .map(|row| Rec {
                section: name,
                cols: &table.columns,
                row,
            })
            .collect())
    }
}

fn map_code(what: &str, code: &str, table: &[(&str, &str)]) -> Result<String> {
    table
        .iter()
        .find(|(k, _)| *k == code)
        .map(|(_, v)| v.to_string())
        .with_context(|| format!("unknown {what} {code:?}"))
}

fn truth(what: &str, v: &str) -> Result<bool> {
    match v {
        "t" | "true" | "1" | "YES" => Ok(true),
        "f" | "false" | "0" | "NO" => Ok(false),
        other => bail!("{what}: {other:?} is not a boolean"),
    }
}

const PG_SCHEMAS: [&str; 2] = ["information_schema", "pg_catalog"];
const MY_SCHEMAS: [&str; 4] = ["information_schema", "mysql", "performance_schema", "sys"];

const PG_RELKINDS: [(&str, &str); 5] = [
    ("r", "table"),
    ("v", "view"),
    ("m", "materialized_view"),
    ("p", "partitioned_table"),
    ("f", "foreign_table"),
];
const MY_TABLE_TYPES: [(&str, &str); 4] = [
    ("BASE TABLE", "table"),
    ("VIEW", "view"),
    ("SYSTEM VIEW", "system_view"),
    ("SEQUENCE", "sequence"),
];
const PG_PROKINDS: [(&str, &str); 4] = [
    ("f", "function"),
    ("a", "aggregate"),
    ("w", "window"),
    ("p", "procedure"),
];
const PG_VOLATILITY: [(&str, &str); 3] = [("i", "immutable"), ("s", "stable"), ("v", "volatile")];
const PG_OPRKINDS: [(&str, &str); 3] = [("b", "infix"), ("l", "prefix"), ("r", "postfix")];
const PG_TYPTYPES: [(&str, &str); 7] = [
    ("b", "base"),
    ("c", "composite"),
    ("d", "domain"),
    ("e", "enum"),
    ("p", "pseudo"),
    ("r", "range"),
    ("m", "multirange"),
];
const MY_ROUTINE_TYPES: [(&str, &str); 2] = [("FUNCTION", "function"), ("PROCEDURE", "procedure")];
const SQLITE_FN_TYPES: [(&str, &str); 3] = [("s", "function"), ("a", "aggregate"), ("w", "window")];

/// `relations` plus their `columns` (any engine): columns by ordinal position.
fn relations(raw: &RawFile, kinds: &[(&str, &str)]) -> Result<Vec<Relation>> {
    let mut out: BTreeMap<(String, String), Relation> = BTreeMap::new();
    for r in raw.records("relations")? {
        let (schema, name) = (r.string("schema")?, r.string("name")?);
        let rel = Relation {
            schema: schema.clone(),
            name: name.clone(),
            kind: map_code("relation kind", r.req("kind")?, kinds)?,
            columns: Vec::new(),
        };
        ensure!(
            out.insert((schema.clone(), name.clone()), rel).is_none(),
            "{}: relation {schema}.{name} twice",
            raw.id
        );
    }
    let mut cols: BTreeMap<(String, String), Vec<(u32, Column)>> = BTreeMap::new();
    for r in raw.records("columns")? {
        let key = (r.string("schema")?, r.string("relation")?);
        let pos: u32 = r
            .req("position")?
            .parse()
            .with_context(|| format!("{}: column position", raw.id))?;
        let col = Column {
            name: r.string("name")?,
            ty: r.string("type")?,
            nullable: truth("nullable", r.req("nullable")?)?,
        };
        cols.entry(key).or_default().push((pos, col));
    }
    for (key, mut list) in cols {
        // A column of a relation the account cannot list is dropped with its relation.
        let Some(rel) = out.get_mut(&key) else {
            continue;
        };
        list.sort_by_key(|(p, _)| *p);
        for w in list.windows(2) {
            ensure!(
                w[0].0 != w[1].0,
                "{}: {}.{} has two columns at {}",
                raw.id,
                key.0,
                key.1,
                w[0].0
            );
        }
        rel.columns = list.into_iter().map(|(_, c)| c).collect();
    }
    Ok(out.into_values().collect())
}

fn coverage(
    raw: &RawFile,
    expected: &[&str],
    rels: &[Relation],
    builtins: Option<&str>,
) -> Coverage {
    let present: BTreeSet<&str> = rels.iter().map(|r| r.schema.as_str()).collect();
    Coverage {
        reader: raw.reader.clone(),
        expected_schemas: expected.iter().map(|s| s.to_string()).collect(),
        missing_schemas: expected
            .iter()
            .filter(|s| !present.contains(*s))
            .map(|s| s.to_string())
            .collect(),
        relations_without_columns: rels.iter().filter(|r| r.columns.is_empty()).count() as u32,
        builtins: builtins.map(str::to_string),
    }
}

fn from_pg(raw: &RawFile) -> Result<Snapshot> {
    let rels = relations(raw, &PG_RELKINDS)?;
    let mut routines = Vec::new();
    for r in raw.records("routines")? {
        let args = r.string("args")?;
        let identity = r.string("identity")?;
        routines.push(Routine {
            schema: Some(r.string("schema")?),
            name: r.string("name")?,
            kind: map_code("prokind", r.req("kind")?, &PG_PROKINDS)?,
            identity: (identity != args).then_some(identity),
            args: Some(args),
            result: r.opt_string("result")?,
            volatility: Some(map_code(
                "provolatile",
                r.req("volatility")?,
                &PG_VOLATILITY,
            )?),
            set_returning: truth("set_returning", r.req("set_returning")?)?,
            arity: None,
            deterministic: None,
            description: r.opt_string("description")?,
        });
    }
    let mut operators = Vec::new();
    for r in raw.records("operators")? {
        operators.push(Operator {
            schema: r.string("schema")?,
            name: r.string("name")?,
            kind: map_code("oprkind", r.req("kind")?, &PG_OPRKINDS)?,
            left: r.opt_string("left")?,
            right: r.opt_string("right")?,
            result: r.string("result")?,
            function: r.string("function")?,
            description: r.opt_string("description")?,
        });
    }
    let mut types = Vec::new();
    for r in raw.records("types")? {
        types.push(TypeDef {
            schema: r.string("schema")?,
            name: r.string("name")?,
            sql_name: r.string("sql_name")?,
            kind: map_code("typtype", r.req("kind")?, &PG_TYPTYPES)?,
            category: r.string("category")?,
            element: r.opt_string("element")?,
            description: r.opt_string("description")?,
        });
    }
    let mut variables = Vec::new();
    for r in raw.records("variables")? {
        variables.push(Variable {
            name: r.string("name")?,
            scope: None,
            ty: r.opt_string("type")?,
            context: r.opt_string("context")?,
        });
    }
    Ok(Snapshot {
        format: FORMAT,
        engine: raw.engine.clone(),
        line: raw.line.clone(),
        server_version: raw.server_version.clone(),
        coverage: coverage(raw, &PG_SCHEMAS, &rels, None),
        relations: rels,
        routines,
        operators,
        types,
        variables,
        lists: BTreeMap::new(),
    })
}

fn from_my(raw: &RawFile) -> Result<Snapshot> {
    let rels = relations(raw, &MY_TABLE_TYPES)?;
    // Parameters by routine, in ordinal order.
    type Key = (String, String, String);
    let mut params: BTreeMap<Key, Vec<(u32, String)>> = BTreeMap::new();
    for r in raw.records("parameters")? {
        let kind = map_code("routine type", r.req("kind")?, &MY_ROUTINE_TYPES)?;
        let key = (r.string("schema")?, r.string("name")?, kind.clone());
        let pos: u32 = r.req("position")?.parse().context("parameter position")?;
        let name = r.opt("param")?.unwrap_or_default();
        let ty = r.req("type")?;
        let text = match (kind.as_str(), r.opt("mode")?) {
            ("procedure", Some(mode)) => format!("{mode} {name} {ty}"),
            _ => format!("{name} {ty}"),
        };
        params.entry(key).or_default().push((pos, text));
    }
    let mut routines = Vec::new();
    for r in raw.records("routines")? {
        let kind = map_code("routine type", r.req("kind")?, &MY_ROUTINE_TYPES)?;
        let key = (r.string("schema")?, r.string("name")?, kind.clone());
        let mut list = params.remove(&key).unwrap_or_default();
        list.sort_by_key(|(p, _)| *p);
        let args: Vec<String> = list.into_iter().map(|(_, t)| t).collect();
        routines.push(Routine {
            schema: Some(key.0),
            name: key.1,
            kind,
            args: Some(args.join(", ")),
            identity: None,
            result: r.opt_string("result")?.filter(|_| key.2 == "function"),
            volatility: None,
            set_returning: false,
            arity: None,
            deterministic: Some(truth("deterministic", r.req("deterministic")?)?),
            description: None,
        });
    }
    let mut sources = BTreeSet::new();
    let mut seen = BTreeSet::new();
    for r in raw.records("builtins")? {
        let name = r.req("name")?.to_ascii_lowercase();
        sources.insert(r.string("source")?);
        if seen.insert(name.clone()) {
            routines.push(Routine {
                schema: None,
                name,
                kind: "function".into(),
                args: None,
                identity: None,
                result: None,
                volatility: None,
                set_returning: false,
                arity: None,
                deterministic: None,
                description: None,
            });
        }
    }
    let mut variables = Vec::new();
    for r in raw.records("variables")? {
        variables.push(Variable {
            name: r.req("name")?.to_ascii_lowercase(),
            scope: r
                .opt("scope")
                .ok()
                .flatten()
                .map(|s| s.to_ascii_lowercase().replace(' ', "_")),
            ty: r.opt("type").ok().flatten().map(|s| s.to_ascii_lowercase()),
            context: None,
        });
    }
    Ok(Snapshot {
        format: FORMAT,
        engine: raw.engine.clone(),
        line: raw.line.clone(),
        server_version: raw.server_version.clone(),
        coverage: coverage(
            raw,
            &MY_SCHEMAS,
            &rels,
            (!sources.is_empty())
                .then(|| sources.into_iter().collect::<Vec<_>>().join("+"))
                .as_deref(),
        ),
        relations: rels,
        routines,
        operators: Vec::new(),
        types: Vec::new(),
        variables,
        lists: BTreeMap::new(),
    })
}

fn from_sqlite(raw: &RawFile) -> Result<Snapshot> {
    let rels = relations(raw, &[("table", "table")])?;
    let mut routines = Vec::new();
    for r in raw.records("functions")? {
        routines.push(Routine {
            schema: None,
            name: r.string("name")?,
            kind: map_code("function type", r.req("kind")?, &SQLITE_FN_TYPES)?,
            args: None,
            identity: None,
            result: None,
            volatility: None,
            set_returning: false,
            arity: Some(r.req("arity")?.parse().context("narg")?),
            deterministic: Some(truth("deterministic", r.req("deterministic")?)?),
            description: None,
        });
    }
    let mut lists = BTreeMap::new();
    for section in ["collations", "modules", "pragmas"] {
        let names = raw
            .records(section)?
            .iter()
            .map(|r| r.string("name"))
            .collect::<Result<Vec<_>>>()?;
        lists.insert(section.to_string(), names);
    }
    Ok(Snapshot {
        format: FORMAT,
        engine: raw.engine.clone(),
        line: raw.line.clone(),
        server_version: raw.server_version.clone(),
        coverage: coverage(raw, &["main"], &rels, None),
        relations: rels,
        routines,
        operators: Vec::new(),
        types: Vec::new(),
        variables: Vec::new(),
        lists,
    })
}

fn from_raw(raw: &RawFile) -> Result<Snapshot> {
    ensure!(
        raw.format == RAW_FORMAT,
        "{}: raw format {:?}, expected {RAW_FORMAT}",
        raw.id,
        raw.format
    );
    let mut s = match raw.engine.as_str() {
        "postgres" => from_pg(raw),
        "mysql" | "mariadb" => from_my(raw),
        "sqlite" => from_sqlite(raw),
        other => bail!("{}: unknown engine {other:?}", raw.id),
    }
    .with_context(|| format!("raw {}", raw.id))?;
    canonicalize(&mut s).with_context(|| format!("raw {}", raw.id))?;
    Ok(s)
}

