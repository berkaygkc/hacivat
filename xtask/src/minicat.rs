// -----------------------------------------------------------------------------------------------
// The snapshot model

/// One engine line's system catalog.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Snapshot {
    pub format: u32,
    /// `postgres`, `mysql`, `mariadb` or `sqlite`.
    pub engine: String,
    /// The server line: `17`, `8.4`, `10.11`; SQLite's major (`3`).
    pub line: String,
    /// The server's version string (`SHOW server_version`, `VERSION()`, `sqlite_version()`).
    pub server_version: String,
    pub coverage: Coverage,
    pub relations: Vec<Relation>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub routines: Vec<Routine>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub operators: Vec<Operator>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub types: Vec<TypeDef>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub variables: Vec<Variable>,
    /// Name lists without structure: SQLite's `pragmas`, `collations`, `modules`.
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    pub lists: BTreeMap<String, Vec<String>>,
}

/// What the read could see. A snapshot is complete when no expected schema is missing and every
/// relation has columns.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Coverage {
    /// `catalog` (the system-schema reader), `test` (the fixture account) or `bundled`.
    pub reader: String,
    pub expected_schemas: Vec<String>,
    pub missing_schemas: Vec<String>,
    pub relations_without_columns: u32,
    /// Where the schema-less built-in function names come from: `probe`, `sql_functions`, or
    /// both joined with `+`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub builtins: Option<String>,
}

impl Coverage {
    pub fn is_complete(&self) -> bool {
        self.missing_schemas.is_empty() && self.relations_without_columns == 0
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Relation {
    pub schema: String,
    pub name: String,
    /// `table`, `view`, `system_view`, `materialized_view`, `partitioned_table`,
    /// `foreign_table`, `sequence`.
    pub kind: String,
    /// In ordinal order.
    pub columns: Vec<Column>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Column {
    pub name: String,
    #[serde(rename = "type")]
    pub ty: String,
    pub nullable: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Routine {
    /// `None` for schema-less built-ins (MySQL/MariaDB native functions, SQLite).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub schema: Option<String>,
    pub name: String,
    /// `function`, `aggregate`, `window`, `procedure`.
    pub kind: String,
    /// The argument list as the server prints it (`None`: not introspectable).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub args: Option<String>,
    /// PostgreSQL's identity arguments, only when they differ from `args` (defaults, OUT).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub identity: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub result: Option<String>,
    /// `immutable`, `stable`, `volatile` (PostgreSQL).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub volatility: Option<String>,
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub set_returning: bool,
    /// SQLite's `narg` (`-1`: variadic).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub arity: Option<i64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub deterministic: Option<bool>,
    /// The server's own description (PostgreSQL only: MySQL and MariaDB comments are GPL text).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Operator {
    pub schema: String,
    pub name: String,
    /// `infix`, `prefix`.
    pub kind: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub left: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub right: Option<String>,
    pub result: String,
    pub function: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct TypeDef {
    pub schema: String,
    pub name: String,
    /// The SQL spelling (`format_type`: `integer` for `int4`).
    pub sql_name: String,
    /// `base`, `composite`, `domain`, `enum`, `pseudo`, `range`, `multirange`.
    pub kind: String,
    pub category: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub element: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Variable {
    pub name: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub scope: Option<String>,
    #[serde(default, rename = "type", skip_serializing_if = "Option::is_none")]
    pub ty: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub context: Option<String>,
}

