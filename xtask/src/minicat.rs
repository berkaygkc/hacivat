    fn my_raw(schemas: &[&str]) -> Value {
        let mut rels: Vec<[Option<&str>; 3]> = Vec::new();
        let mut cols: Vec<[Option<&str>; 6]> = Vec::new();
        for s in schemas {
            rels.push([Some(s), Some("t1"), Some("SYSTEM VIEW")]);
            cols.push([
                Some(s),
                Some("t1"),
                Some("1"),
                Some("C1"),
                Some("varchar(64)"),
                Some("NO"),
            ]);
        }
        json!({
            "format": RAW_FORMAT, "id": "mysql84", "engine": "mysql", "line": "8.4",
            "server_version": "8.4.0", "reader": "catalog",
            "sections": {
                "relations": json!({"columns": ["schema", "name", "kind"], "rows": rels}),
                "columns": json!({"columns": ["schema", "relation", "position", "name", "type", "nullable"], "rows": cols}),
                "routines": table(&["schema", "name", "kind", "result", "deterministic"], &[
                    &[Some("sys"), Some("format_bytes"), Some("FUNCTION"), Some("text"), Some("YES")],
                    &[Some("sys"), Some("ps_setup_reset_to_default"), Some("PROCEDURE"), None, Some("NO")],
                ]),
                "parameters": table(&["schema", "name", "kind", "position", "mode", "param", "type"], &[
                    &[Some("sys"), Some("format_bytes"), Some("FUNCTION"), Some("1"), None, Some("bytes"), Some("text")],
                    &[Some("sys"), Some("ps_setup_reset_to_default"), Some("PROCEDURE"), Some("1"), Some("IN"), Some("in_verbose"), Some("tinyint(1)")],
                ]),
                "variables": table(&["name"], &[&[Some("sql_mode")], &[Some("autocommit")]]),
                "builtins": table(&["name", "source"], &[&[Some("CONCAT"), Some("probe")], &[Some("abs"), Some("probe")]]),
            }
        })
    }

    fn sqlite_raw() -> Value {
        json!({
            "format": RAW_FORMAT, "id": "sqlite", "engine": "sqlite", "line": "3",
            "server_version": "3.50.0", "reader": "bundled",
            "sections": {
                "relations": table(&["schema", "name", "kind"], &[&[Some("main"), Some("sqlite_schema"), Some("table")]]),
                "columns": table(&["schema", "relation", "position", "name", "type", "nullable"], &[
                    &[Some("main"), Some("sqlite_schema"), Some("1"), Some("type"), Some("TEXT"), Some("true")],
                ]),
                "functions": table(&["name", "kind", "arity", "deterministic"], &[
                    &[Some("substr"), Some("s"), Some("2"), Some("1")],
                    &[Some("substr"), Some("s"), Some("3"), Some("1")],
                    &[Some("count"), Some("a"), Some("0"), Some("0")],
                ]),
                "pragmas": table(&["name"], &[&[Some("table_info")], &[Some("foreign_keys")]]),
                "collations": table(&["name"], &[&[Some("NOCASE")], &[Some("BINARY")]]),
                "modules": table(&["name"], &[&[Some("json_each")]]),
            }
        })
    }

    fn write_raws(dir: &Path, docs: &[Value]) {
        for d in docs {
            let id = d["id"].as_str().unwrap();
            std::fs::write(
                dir.join(format!("{id}.json")),
                serde_json::to_vec(d).unwrap(),
            )
            .unwrap();
        }
    }

    /// Every `rows` array of a raw document reversed: the read's row order must not matter.
    fn reversed(mut d: Value) -> Value {
        for (_, t) in d["sections"].as_object_mut().unwrap() {
            t["rows"].as_array_mut().unwrap().reverse();
        }
        d
    }

    fn all() -> Vec<Value> {
        vec![
            pg_raw(),
            my_raw(&["information_schema", "mysql", "performance_schema", "sys"]),
            sqlite_raw(),
        ]
    }

    fn built(docs: &[Value]) -> tempfile::TempDir {
        let raw = tempfile::tempdir().unwrap();
        write_raws(raw.path(), docs);
        let out = tempfile::tempdir().unwrap();
        build(raw.path(), out.path(), false).unwrap();
        out
    }

