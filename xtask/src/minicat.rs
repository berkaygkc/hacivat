#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Manifest {
    pub format: u32,
    pub zstd_level: i32,
    /// The libzstd version that encoded the files (`check` re-encodes with the linked one).
    pub zstd_library: String,
    pub snapshot: Vec<Entry>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Entry {
    pub file: String,
    pub engine: String,
    pub line: String,
    pub server_version: String,
    /// The pinned image the line was read from (`docker/m2a/compose.yml`); none for SQLite.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub image: Option<String>,
    /// `complete` or `partial`.
    pub coverage: String,
    pub json_bytes: u64,
    pub zst_bytes: u64,
    pub json_digest: String,
    pub zst_digest: String,
    pub relations: u64,
    pub columns: u64,
    pub routines: u64,
    pub operators: u64,
    pub types: u64,
    pub variables: u64,
}

fn entry_of(s: &Snapshot, image: Option<String>, json: &[u8], zst: &[u8]) -> Entry {
    Entry {
        file: file_name(&s.engine, &s.line),
        engine: s.engine.clone(),
        line: s.line.clone(),
        server_version: s.server_version.clone(),
        image,
        coverage: if s.coverage.is_complete() {
            "complete"
        } else {
            "partial"
        }
        .into(),
        json_bytes: json.len() as u64,
        zst_bytes: zst.len() as u64,
        json_digest: xxh3(json),
        zst_digest: xxh3(zst),
        relations: s.relations.len() as u64,
        columns: s.relations.iter().map(|r| r.columns.len() as u64).sum(),
        routines: s.routines.len() as u64,
        operators: s.operators.len() as u64,
        types: s.types.len() as u64,
        variables: s.variables.len() as u64,
    }
}

fn zstd_library() -> String {
    zstd::zstd_safe::version_string().to_string()
}

fn manifest_text(m: &Manifest) -> Result<String> {
    Ok(format!(
        "{MANIFEST_HEADER}{}",
        toml::to_string(m).context("manifest TOML")?
    ))
}

