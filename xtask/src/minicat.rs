//! `xtask minicat collect | build | check`: the system-catalog snapshots (HV-INTRO-16, L7,
//! D-017; M4 pre-work spike). One snapshot per engine line (PostgreSQL 14–18, MySQL 8.0/8.4,
//! MariaDB 10.6/10.11/11.4, the bundled SQLite) holds the *system* schemas' relations and
//! columns, routines with signatures, operators, types, system variable names and a few named
//! lists, so completion and the explorer know built-in objects offline. The installer bundles
//! `assets/system-catalogs/` and the model overlays it on live catalogs (M4).
//!
//! - `collect [--reader catalog|test] [--twice] [--require-complete] [--work <dir>]
//!   [--out <dir>]` checks that the `full` set of `docker/m2a` is healthy (it never starts or
//!   stops a container), runs the catalog read (`hacivat-exec/tests/minicat_read.rs`, a Docker
//!   test; xtask has no database client, P-M3b-13) into `<work>/raw-1`, then builds. With
//!   `--twice` it reads and builds a second time from scratch and fails unless every output
//!   file is byte-identical.
//! - `build --raw <dir> [--out <dir>] [--require-complete]` turns raw read files into snapshots
//!   and `manifest.toml`; output files of lines that are no longer read are removed.
//! - `check [--dir <dir>]` (offline): the manifest names exactly the snapshot files, every
//!   digest and count matches, every snapshot decodes, is canonical, and re-encodes to the same
//!   bytes. A unit test runs it on the committed assets, so every PR checks them.
//! - `verify [--reader catalog|test] [--twice] [--work <dir>]`: reads and builds into
//!   `<work>/verify` (complete coverage required) and byte-compares with the committed assets.
//!   `minicat --check` and `minicat --verify` (the M4 plan's spelling) are the same commands.
//!
//! Files: `assets/system-catalogs/<engine>-<line>.hvsnap.zst` (a zstd frame of the canonical
//! JSON below) and `manifest.toml` (per file: exact server version, pinned image, coverage,
//! sizes, counts, xxh3 digests of the JSON and of the frame).
//!
//! Determinism: the build sorts every list by byte order (no collation, no locale), keeps
//! columns in ordinal order, writes no timestamp, host name or path, and compresses with one
//! fixed zstd level, single-threaded, without a dictionary. The zstd library is pinned by
//! `Cargo.lock`; `check` notices a library whose output differs (re-encoding no longer matches).

