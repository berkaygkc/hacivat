/// One server line's system catalog.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Snapshot {
    pub format: u32,
    /// `postgres`, `mysql` or `mariadb`.
    pub dbms: String,
    /// The server line: `17`, `8.4`, `10.11`.
    pub line: String,
    /// The exact server version (`17.6`, `8.4.6`).
    pub server_version: String,
    pub coverage: Coverage,
    pub relations: Vec<Relation>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub routines: Vec<Routine>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub operators: Vec<Operator>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub types: Vec<TypeDef>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub variables: Vec<Variable>,
}

/// What the read could see.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Coverage {
    /// `catalog` (the system-schema reader) or `test` (the fixture account).
    pub reader: String,
    pub expected_schemas: Vec<String>,
    pub missing_schemas: Vec<String>,
    pub relations_without_columns: u32,
    /// Where the schema-less built-in function names come from: `probe`, `sql_functions`, or
    /// both joined with `+`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub builtins: Option<String>,
}

impl Snapshot {
    /// No expected schema missing, every relation with columns, and the built-in names read
    /// from every source of the engine: the probe on MySQL, the probe and
    /// `information_schema.SQL_FUNCTIONS` on MariaDB (R-M4-44; fix round 1, review I-1).
    pub fn is_complete(&self) -> bool {
        let c = &self.coverage;
        let builtins = match self.dbms.as_str() {
            "postgres" => true,
            "mariadb" => c.builtins.as_deref() == Some("probe+sql_functions"),
            _ => c.builtins.as_deref() == Some("probe"),
        };
        c.missing_schemas.is_empty() && c.relations_without_columns == 0 && builtins
    }
}

