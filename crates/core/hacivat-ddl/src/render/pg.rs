//! The PostgreSQL renderer (13–18). M4 Task 7 body (spike origin `da358e4`).
//!
//! PostgreSQL specifics (alg/03 HV-DDL-07 matrix): comments are separate `COMMENT ON`
//! statements after their object; identity columns `GENERATED … AS IDENTITY`; server text
//! (`pg_get_viewdef`, `pg_get_functiondef`, `pg_get_triggerdef`) emitted verbatim; routines are
//! always named with their argument types; minimal clauses (defaults of the server are left
//! out: `heap`, `btree`, sequence bounds).

use hacivat_meta::kind::ObjectKind;
use hacivat_meta::name::Name;
use hacivat_meta::props::{Identity, TypeBody};
use sql_ident::QualifiedName;

use super::{
    RenderCtx, RenderError, Renderer, Stmt, TxnClass, check_option, create_flags, deferrable_tail,
    element_block, fk_action, fk_match, index_part, privilege, stmt, trim_server_text, unsupported,
};
use crate::ir::*;
use crate::produce::placement::Position;

/// Renders the IR as PostgreSQL text.
#[derive(Debug, Clone, Copy)]
pub struct PgRenderer;

const TX: TxnClass = TxnClass::Transactional;

impl Renderer for PgRenderer {
    fn render(&self, op: &DdlOp, ctx: &RenderCtx) -> Result<Vec<Stmt>, RenderError> {
        match op {
            DdlOp::CreateSchema(s) => schema(ctx, s),
            DdlOp::CreateTable(t) => table(ctx, t),
            DdlOp::AlterTable { table, actions } => alter_table(ctx, op, table, actions),
            DdlOp::CreateIndex(i) => index(ctx, i),
            DdlOp::CreateView(v) => view(ctx, v),
            DdlOp::CreateRoutine(r) => routine(ctx, r),
            DdlOp::CreateTrigger(t) => trigger(ctx, t),
            DdlOp::CreateSequence(s) => sequence(ctx, s),
            DdlOp::CreateType(t) => type_def(ctx, op, t),
            DdlOp::Comment { target, text } => Ok(vec![comment(ctx, op, target, text.as_deref())?]),
            DdlOp::Grant(g) => Ok(vec![grant(ctx, op, g)?]),
            DdlOp::Owner {
                kind,
                name,
                sig,
                owner,
            } => Ok(vec![owner_stmt(
                ctx,
                op,
                *kind,
                name,
                sig.as_deref(),
                owner,
            )?]),
            DdlOp::RowSecurity { table, enable } => Ok(vec![stmt(
                format!(
                    "ALTER TABLE {} {} ROW LEVEL SECURITY",
                    ctx.qname(table)?,
                    if *enable { "ENABLE" } else { "DISABLE" }
                ),
                TX,
            )]),
            DdlOp::Raw {
                sql,
                origin: RawOrigin::ServerText,
            } => Ok(vec![stmt(trim_server_text(sql).to_string(), TX)]),
            _ => Err(unsupported(op, ctx)),
        }
    }
}

fn schema(ctx: &RenderCtx, s: &SchemaDef) -> Result<Vec<Stmt>, RenderError> {
    let (_, ine) = create_flags(ctx, ObjectKind::Schema, false, s.if_not_exists);
    let ine = if ine { "IF NOT EXISTS " } else { "" };
    let mut out = vec![stmt(
        format!("CREATE SCHEMA {ine}{}", ctx.ident(&s.name)?),
        TX,
    )];
    if let Some(c) = &s.comment {
        out.push(comment_on(
            ctx,
            &format!("SCHEMA {}", ctx.ident(&s.name)?),
            Some(c),
        )?);
    }
    Ok(out)
}

/// One column definition with the constraints placed inside it.
fn column(
    ctx: &RenderCtx,
    c: &ColumnDef,
    inline: &[&ConstraintDef],
) -> Result<String, RenderError> {
    // ## m4-t19-produce
    if c.invisible {
        return Err(RenderError::Invalid("an invisible column on PostgreSQL"));
    }
    // ## end m4-t19-produce
    let mut s = format!("{} {}", ctx.ident(&c.name)?, c.raw_type);
    if let Some(coll) = &c.collation {
        s.push_str(" COLLATE ");
        s.push_str(&ctx.ident(coll)?);
    }
    if let Some(g) = &c.generated {
        s.push_str(&format!(
            " GENERATED ALWAYS AS ({}) {}",
            g.expr,
            if g.stored { "STORED" } else { "VIRTUAL" }
        ));
    } else {
        match c.identity {
            Some(Identity::Always) => s.push_str(" GENERATED ALWAYS AS IDENTITY"),
            Some(Identity::ByDefault) => s.push_str(" GENERATED BY DEFAULT AS IDENTITY"),
            Some(Identity::AutoIncrement | Identity::RowidAlias) => {
                return Err(RenderError::Invalid(
                    "an auto-increment column on PostgreSQL",
                ));
            }
            None => {
                if let Some(d) = &c.default_raw {
                    s.push_str(" DEFAULT ");
                    s.push_str(d);
                }
            }
        }
    }
    if !c.nullable {
        s.push_str(" NOT NULL");
    }
    for k in inline {
        s.push(' ');
        s.push_str(&constraint(ctx, k, true)?);
    }
    Ok(s)
}

/// A constraint as a table element (`inline = false`, also the text after `ALTER TABLE …
/// ADD`) or inside its column.
fn constraint(ctx: &RenderCtx, k: &ConstraintDef, inline: bool) -> Result<String, RenderError> {
    let mut s = String::new();
    if let Some(n) = &k.name {
        s.push_str("CONSTRAINT ");
        s.push_str(&ctx.ident(n)?);
        s.push(' ');
    }
    match &k.body {
        ConstraintBody::PrimaryKey { columns } => {
            s.push_str("PRIMARY KEY");
            if !inline {
                s.push(' ');
                s.push_str(&ctx.ident_list(columns)?);
            }
        }
        ConstraintBody::Unique {
            columns,
            nulls_not_distinct,
        } => {
            s.push_str("UNIQUE");
            if *nulls_not_distinct {
                s.push_str(" NULLS NOT DISTINCT");
            }
            if !inline {
                s.push(' ');
                s.push_str(&ctx.ident_list(columns)?);
            }
        }
        ConstraintBody::ForeignKey {
            columns,
            target,
            target_columns,
            on_update,
            on_delete,
            match_kind,
        } => {
            if !inline {
                s.push_str("FOREIGN KEY ");
                s.push_str(&ctx.ident_list(columns)?);
                s.push(' ');
            }
            s.push_str("REFERENCES ");
            s.push_str(&ctx.qname(target)?);
            if !target_columns.is_empty() {
                s.push(' ');
                s.push_str(&ctx.ident_list(target_columns)?);
            }
            // `pg_get_constraintdef` order: MATCH, ON UPDATE, ON DELETE.
            s.push_str(fk_match(*match_kind));
            if let Some(a) = fk_action(*on_update) {
                s.push_str(" ON UPDATE ");
                s.push_str(a);
            }
            if let Some(a) = fk_action(*on_delete) {
                s.push_str(" ON DELETE ");
                s.push_str(a);
            }
        }
        ConstraintBody::Check { expr, no_inherit } => {
            s.push_str(&format!("CHECK ({expr})"));
            // ## m4-t13-assemble (R-W2-8)
            if *no_inherit {
                s.push_str(" NO INHERIT");
            }
        }
        ConstraintBody::Exclusion { raw } => {
            if inline {
                return Err(RenderError::Invalid("EXCLUDE inside a column"));
            }
            s.push_str("EXCLUDE ");
            s.push_str(raw);
        }
    }
    s.push_str(deferrable_tail(k.deferrable));
    Ok(s)
}

/// `ALTER TABLE t ADD <constraint> [NOT VALID]`.
fn add_constraint(
    ctx: &RenderCtx,
    table: &QualifiedName,
    k: &ConstraintDef,
) -> Result<Stmt, RenderError> {
    let mut s = format!(
        "ALTER TABLE {} ADD {}",
        ctx.qname(table)?,
        constraint(ctx, k, false)?
    );
    if k.not_valid {
        s.push_str(" NOT VALID");
    }
    Ok(stmt(s, TX))
}

fn table(ctx: &RenderCtx, t: &TableDef) -> Result<Vec<Stmt>, RenderError> {
    let ext = match &t.ext {
        TableDefExt::Pg(p) => p.clone(),
        TableDefExt::None => PgTableDef::default(),
        _ => return Err(RenderError::Invalid("another dialect's table clauses")),
    };
    let placed = ctx.place(&t.constraints, None);
    let mut items = Vec::new();
    for c in &t.columns {
        let inline: Vec<&ConstraintDef> = t
            .constraints
            .iter()
            .zip(&placed)
            .filter(|(_, p)| matches!(&p.position, Position::InColumn(n) if *n == c.name))
            .map(|(k, _)| k)
            .collect();
        items.push(column(ctx, c, &inline)?);
    }
    for (k, p) in t.constraints.iter().zip(&placed) {
        if p.position == Position::InTable {
            items.push(constraint(ctx, k, false)?);
        }
    }
    let mut s = String::from("CREATE ");
    if ext.temporary {
        s.push_str("TEMPORARY ");
    } else if ext.unlogged {
        s.push_str("UNLOGGED ");
    }
    s.push_str("TABLE ");
    let (_, ine) = create_flags(ctx, ObjectKind::Table, false, t.if_not_exists);
    if ine {
        s.push_str("IF NOT EXISTS ");
    }
    s.push_str(&ctx.qname(&t.name)?);
    if let Some((parent, bound)) = &ext.partition_of {
        s.push_str(" PARTITION OF ");
        s.push_str(&ctx.qname(parent)?);
        if !items.is_empty() {
            s.push(' ');
            s.push_str(&element_block(&items));
        }
        s.push(' ');
        s.push_str(bound);
    } else {
        s.push(' ');
        s.push_str(&element_block(&items));
        if !ext.inherits.is_empty() {
            let parents: Result<Vec<String>, _> =
                ext.inherits.iter().map(|p| ctx.qname(p)).collect();
            s.push_str(&format!("\nINHERITS ({})", parents?.join(", ")));
        }
    }
    if let Some(p) = &ext.partition_by {
        s.push_str("\nPARTITION BY ");
        s.push_str(p);
    }
    if let Some(am) = &ext.access_method
        && !am.eq_ignore_ascii_case("heap")
    {
        s.push_str("\nUSING ");
        s.push_str(&ctx.ident(am)?);
    }
    if !ext.with.is_empty() {
        s.push_str(&format!("\nWITH ({})", ext.with.join(", ")));
    }
    if let Some(ts) = &ext.tablespace {
        s.push_str("\nTABLESPACE ");
        s.push_str(&ctx.ident(ts)?);
    }
    let mut out = vec![stmt(s, TX)];
    for (k, p) in t.constraints.iter().zip(&placed) {
        if p.position == Position::After {
            out.push(add_constraint(ctx, &t.name, k)?);
        }
    }
    let table_name = ctx.qname(&t.name)?;
    if let Some(c) = &t.comment {
        out.push(comment_on(ctx, &format!("TABLE {table_name}"), Some(c))?);
    }
    for c in &t.columns {
        if let Some(text) = &c.comment {
            let what = format!("COLUMN {table_name}.{}", ctx.ident(&c.name)?);
            out.push(comment_on(ctx, &what, Some(text))?);
        }
    }
    Ok(out)
}

fn alter_table(
    ctx: &RenderCtx,
    op: &DdlOp,
    table: &QualifiedName,
    actions: &[AlterAction],
) -> Result<Vec<Stmt>, RenderError> {
    let mut out = Vec::new();
    for a in actions {
        match a {
            AlterAction::AddConstraint(k) => out.push(add_constraint(ctx, table, k)?),
            _ => return Err(unsupported(op, ctx)),
        }
    }
    Ok(out)
}

/// The index's own name in its table's schema (`schema.index`).
fn index_name(ctx: &RenderCtx, i: &IndexDef) -> Result<String, RenderError> {
    let mut parts = i.table.clone();
    let last = parts
        .parts
        .last_mut()
        .ok_or(RenderError::Invalid("a name without parts"))?;
    last.text = i.name.clone();
    ctx.qname(&parts)
}

fn index(ctx: &RenderCtx, i: &IndexDef) -> Result<Vec<Stmt>, RenderError> {
    let mut s = String::from("CREATE ");
    if i.unique {
        s.push_str("UNIQUE ");
    }
    s.push_str("INDEX ");
    if i.concurrently {
        s.push_str("CONCURRENTLY ");
    }
    let (_, ine) = create_flags(ctx, ObjectKind::Index, false, i.if_not_exists);
    if ine {
        s.push_str("IF NOT EXISTS ");
    }
    s.push_str(&ctx.ident(&i.name)?);
    s.push_str(" ON ");
    s.push_str(&ctx.qname(&i.table)?);
    if let Some(m) = &i.method
        && !m.eq_ignore_ascii_case("btree")
    {
        s.push_str(" USING ");
        s.push_str(&ctx.ident(m)?);
    }
    let parts: Result<Vec<String>, _> = i.parts.iter().map(|p| index_part(ctx, p)).collect();
    s.push_str(&format!(" ({})", parts?.join(", ")));
    if !i.include.is_empty() {
        s.push_str(" INCLUDE ");
        s.push_str(&ctx.ident_list(&i.include)?);
    }
    if i.nulls_not_distinct {
        s.push_str(" NULLS NOT DISTINCT");
    }
    if let Some(p) = &i.predicate {
        s.push_str(" WHERE ");
        s.push_str(p);
    }
    let txn = if i.concurrently {
        TxnClass::NonTransactional
    } else {
        TX
    };
    let mut out = vec![stmt(s, txn)];
    if let Some(c) = &i.comment {
        out.push(comment_on(
            ctx,
            &format!("INDEX {}", index_name(ctx, i)?),
            Some(c),
        )?);
    }
    Ok(out)
}

fn view(ctx: &RenderCtx, v: &ViewDef) -> Result<Vec<Stmt>, RenderError> {
    let kind = match v.kind {
        ViewKind::View => ObjectKind::View,
        ViewKind::Materialized => ObjectKind::MaterializedView,
    };
    let (or_replace, ine) = create_flags(ctx, kind, v.or_replace, false);
    let mut s = String::from("CREATE ");
    if or_replace {
        s.push_str("OR REPLACE ");
    }
    s.push_str(match v.kind {
        ViewKind::View => "VIEW ",
        ViewKind::Materialized => "MATERIALIZED VIEW ",
    });
    if ine {
        s.push_str("IF NOT EXISTS ");
    }
    let name = ctx.qname(&v.name)?;
    s.push_str(&name);
    s.push_str(" AS\n");
    s.push_str(trim_server_text(&v.body));
    if let Some(opt) = &v.check_option {
        s.push_str(&format!("\n  WITH {} CHECK OPTION", check_option(opt)?));
    }
    let word = match v.kind {
        ViewKind::View => "VIEW",
        ViewKind::Materialized => "MATERIALIZED VIEW",
    };
    let mut out = vec![stmt(s, TX)];
    if let Some(c) = &v.comment {
        out.push(comment_on(ctx, &format!("{word} {name}"), Some(c))?);
    }
    for (col, text) in &v.column_comments {
        let what = format!("COLUMN {name}.{}", ctx.ident(col)?);
        out.push(comment_on(ctx, &what, Some(text))?);
    }
    Ok(out)
}

fn routine(ctx: &RenderCtx, r: &RoutineDef) -> Result<Vec<Stmt>, RenderError> {
    let mut out = vec![stmt(trim_server_text(&r.text).to_string(), TX)];
    if let Some(c) = &r.comment {
        let what = format!(
            "{} {}",
            routine_word(r.kind),
            routine_ref(ctx, &r.name, r.sig.as_deref())?
        );
        out.push(comment_on(ctx, &what, Some(c))?);
    }
    Ok(out)
}

/// `pg_get_triggerdef` text; with `or_replace` on 14+ a plain `CREATE TRIGGER` head becomes
/// `CREATE OR REPLACE TRIGGER` (a constraint trigger has no such form and stays as it is).
fn trigger(ctx: &RenderCtx, t: &TriggerDef) -> Result<Vec<Stmt>, RenderError> {
    let text = trim_server_text(&t.text);
    let (or_replace, _) = create_flags(ctx, ObjectKind::Trigger, false, false);
    const HEAD: &str = "CREATE TRIGGER ";
    let text = match text.get(..HEAD.len()) {
        Some(head) if or_replace && head.eq_ignore_ascii_case(HEAD) => {
            format!("CREATE OR REPLACE TRIGGER {}", &text[HEAD.len()..])
        }
        _ => text.to_string(),
    };
    let mut out = vec![stmt(text, TX)];
    if let Some(c) = &t.comment {
        let what = format!(
            "TRIGGER {} ON {}",
            ctx.ident(&t.name)?,
            ctx.qname(&t.table)?
        );
        out.push(comment_on(ctx, &what, Some(c))?);
    }
    Ok(out)
}

/// `(min, max)` of a PostgreSQL sequence type; `bigint`'s for anything else.
fn seq_bounds(ty: Option<&str>) -> (i64, i64) {
    match ty {
        Some(t) if t.eq_ignore_ascii_case("smallint") => (i64::from(i16::MIN), i64::from(i16::MAX)),
        Some(t) if t.eq_ignore_ascii_case("integer") => (i64::from(i32::MIN), i64::from(i32::MAX)),
        _ => (i64::MIN, i64::MAX),
    }
}

/// The clauses of a sequence that differ from the server's defaults (`CREATE SEQUENCE`
/// docs): increment 1; ascending min 1 and max the type's maximum; descending min the type's
/// minimum and max -1; start at min (ascending) or max (descending); cache 1; no cycle.
fn sequence(ctx: &RenderCtx, q: &SeqDef) -> Result<Vec<Stmt>, RenderError> {
    let ty = q.data_type.as_deref();
    let (tmin, tmax) = seq_bounds(ty);
    let inc = q.increment.unwrap_or(1);
    let asc = inc > 0;
    let (dmin, dmax) = if asc { (1, tmax) } else { (tmin, -1) };
    let min = q.min.unwrap_or(dmin);
    let max = q.max.unwrap_or(dmax);
    let dstart = if asc { min } else { max };
    let mut clauses = Vec::new();
    if let Some(t) = ty
        && !t.eq_ignore_ascii_case("bigint")
    {
        clauses.push(format!("AS {t}"));
    }
    if inc != 1 {
        clauses.push(format!("INCREMENT BY {inc}"));
    }
    if min != dmin {
        clauses.push(format!("MINVALUE {min}"));
    }
    if max != dmax {
        clauses.push(format!("MAXVALUE {max}"));
    }
    if let Some(s) = q.start
        && s != dstart
    {
        clauses.push(format!("START WITH {s}"));
    }
    if let Some(c) = q.cache
        && c != 1
    {
        clauses.push(format!("CACHE {c}"));
    }
    if q.cycle {
        clauses.push("CYCLE".to_string());
    }
    if let Some((table, col)) = &q.owned_by {
        clauses.push(format!(
            "OWNED BY {}.{}",
            ctx.qname(table)?,
            ctx.ident(col)?
        ));
    }
    let (_, ine) = create_flags(ctx, ObjectKind::Sequence, false, q.if_not_exists);
    let name = ctx.qname(&q.name)?;
    let mut s = format!(
        "CREATE SEQUENCE {}{name}",
        if ine { "IF NOT EXISTS " } else { "" }
    );
    for c in clauses {
        s.push_str("\n    ");
        s.push_str(&c);
    }
    let mut out = vec![stmt(s, TX)];
    if let Some(c) = &q.comment {
        out.push(comment_on(ctx, &format!("SEQUENCE {name}"), Some(c))?);
    }
    Ok(out)
}

fn type_def(ctx: &RenderCtx, op: &DdlOp, t: &TypeDef) -> Result<Vec<Stmt>, RenderError> {
    let name = ctx.qname(&t.name)?;
    let (text, word) = match &t.body {
        TypeBody::Enum { labels } => {
            let lits: Result<Vec<String>, _> = labels.iter().map(|l| ctx.literal(l)).collect();
            let lits = lits?;
            let body = if lits.is_empty() {
                "()".to_string()
            } else {
                format!("(\n    {}\n)", lits.join(",\n    "))
            };
            (format!("CREATE TYPE {name} AS ENUM {body}"), "TYPE")
        }
        TypeBody::Domain {
            base,
            not_null,
            not_null_constraint,
            default_raw,
            checks,
        } => {
            let mut s = format!("CREATE DOMAIN {name} AS {base}");
            if let Some(d) = default_raw {
                s.push_str("\n    DEFAULT ");
                s.push_str(d);
            }
            if *not_null {
                s.push_str("\n    ");
                if let Some(cn) = not_null_constraint {
                    s.push_str(&format!("CONSTRAINT {} ", ctx.ident(cn)?));
                }
                s.push_str("NOT NULL");
            }
            for expr in checks {
                s.push_str(&format!("\n    CHECK ({expr})"));
            }
            (s, "DOMAIN")
        }
        TypeBody::Composite { attrs } => {
            let items: Result<Vec<String>, RenderError> = attrs
                .iter()
                .map(|a| Ok(format!("{} {}", ctx.ident(&a.name)?, a.raw_type)))
                .collect();
            (
                format!("CREATE TYPE {name} AS {}", element_block(&items?)),
                "TYPE",
            )
        }
        TypeBody::Range { subtype } => (
            format!("CREATE TYPE {name} AS RANGE (\n    subtype = {subtype}\n)"),
            "TYPE",
        ),
        // A base type needs C functions: no CREATE script.
        TypeBody::Base => return Err(unsupported(op, ctx)),
    };
    let mut out = vec![stmt(text, TX)];
    if let Some(c) = &t.comment {
        out.push(comment_on(ctx, &format!("{word} {name}"), Some(c))?);
    }
    Ok(out)
}

/// The object-type words of `COMMENT ON`, `ALTER … OWNER TO` and `GRANT … ON`.
fn kind_word(kind: ObjectKind) -> Option<&'static str> {
    use ObjectKind::*;
    Some(match kind {
        Schema => "SCHEMA",
        Database => "DATABASE",
        Table | Partition => "TABLE",
        View => "VIEW",
        MaterializedView => "MATERIALIZED VIEW",
        ForeignTable => "FOREIGN TABLE",
        Index => "INDEX",
        Sequence => "SEQUENCE",
        Domain => "DOMAIN",
        EnumType | CompositeType | RangeType => "TYPE",
        Extension => "EXTENSION",
        k if is_routine(k) => routine_word(k),
        _ => return None,
    })
}

fn is_routine(kind: ObjectKind) -> bool {
    matches!(
        kind,
        ObjectKind::Routine | ObjectKind::Procedure | ObjectKind::Aggregate
    )
}

fn routine_word(kind: ObjectKind) -> &'static str {
    match kind {
        ObjectKind::Procedure => "PROCEDURE",
        ObjectKind::Aggregate => "AGGREGATE",
        _ => "FUNCTION",
    }
}

/// `name(argument types)`: a routine is never named without its signature, which could
/// mean another overload.
fn routine_ref(
    ctx: &RenderCtx,
    name: &QualifiedName,
    sig: Option<&str>,
) -> Result<String, RenderError> {
    let sig = sig.ok_or(RenderError::Invalid(
        "a routine named without its argument types",
    ))?;
    Ok(format!("{}({sig})", ctx.qname(name)?))
}

/// `COMMENT ON <what> IS '…'` (`IS NULL` removes the comment).
fn comment_on(ctx: &RenderCtx, what: &str, text: Option<&str>) -> Result<Stmt, RenderError> {
    let lit = match text {
        Some(s) => ctx.literal(s)?,
        None => "NULL".to_string(),
    };
    Ok(stmt(format!("COMMENT ON {what} IS {lit}"), TX))
}

/// A standalone comment. Triggers and constraints carry their table in their own defs; a
/// standalone comment on one is M7's.
fn comment(
    ctx: &RenderCtx,
    op: &DdlOp,
    t: &CommentTarget,
    text: Option<&str>,
) -> Result<Stmt, RenderError> {
    let what = match t.kind {
        ObjectKind::Column => {
            let col = t
                .column
                .as_ref()
                .ok_or(RenderError::Invalid("a column comment without its column"))?;
            format!("COLUMN {}.{}", ctx.qname(&t.name)?, ctx.ident(col)?)
        }
        k if is_routine(k) => format!(
            "{} {}",
            routine_word(k),
            routine_ref(ctx, &t.name, t.sig.as_deref())?
        ),
        k => {
            let word = kind_word(k).ok_or_else(|| unsupported(op, ctx))?;
            format!("{word} {}", ctx.qname(&t.name)?)
        }
    };
    comment_on(ctx, &what, text)
}

fn object_ref(
    ctx: &RenderCtx,
    op: &DdlOp,
    kind: ObjectKind,
    name: &QualifiedName,
    sig: Option<&str>,
) -> Result<String, RenderError> {
    let word = kind_word(kind).ok_or_else(|| unsupported(op, ctx))?;
    Ok(if is_routine(kind) {
        format!("{word} {}", routine_ref(ctx, name, sig)?)
    } else {
        format!("{word} {}", ctx.qname(name)?)
    })
}

fn owner_stmt(
    ctx: &RenderCtx,
    op: &DdlOp,
    kind: ObjectKind,
    name: &QualifiedName,
    sig: Option<&str>,
    owner: &Name,
) -> Result<Stmt, RenderError> {
    // An index belongs to its table's owner; an extension has no `ALTER EXTENSION … OWNER
    // TO` (only `COMMENT ON EXTENSION` exists).
    if matches!(kind, ObjectKind::Index | ObjectKind::Extension) {
        return Err(unsupported(op, ctx));
    }
    // ## m4-t33a-hygiene (named exception in Task 19's file; T16b review m-1)
    if &**owner == "PUBLIC" {
        return Err(RenderError::Invalid("PUBLIC owns nothing"));
    }
    let owner = role(ctx, owner)?;
    // ## m4-t33a-hygiene
    Ok(stmt(
        format!(
            "ALTER {} OWNER TO {owner}",
            object_ref(ctx, op, kind, name, sig)?,
        ),
        TX,
    ))
}

// ## m4-t33a-hygiene (T16b review m-1 carry to this renderer)
/// A role name in a `RoleSpec` position (`GRANT … TO`, `OWNER TO`). PostgreSQL's role grammar
/// reads `public` as PUBLIC and refuses `none`, quoted or not (it compares the folded or
/// quoted text case-sensitively), so no quoting can name a role of that name: refused, never
/// a grant to everyone. Every other name goes through `ctx.ident` (reserved words such as
/// `current_user` are quoted, so they name the role, not the keyword).
fn role(ctx: &RenderCtx, name: &Name) -> Result<String, RenderError> {
    if matches!(&**name, "public" | "none") {
        return Err(RenderError::Invalid(
            "a role name PostgreSQL reads as a keyword",
        ));
    }
    ctx.ident(name)
}
// ## m4-t33a-hygiene

fn grant(ctx: &RenderCtx, op: &DdlOp, g: &GrantDef) -> Result<Stmt, RenderError> {
    // Views, materialized views and foreign tables are granted `ON TABLE`; aggregates `ON
    // FUNCTION`.
    let kind = match g.kind {
        ObjectKind::View | ObjectKind::MaterializedView | ObjectKind::ForeignTable => {
            ObjectKind::Table
        }
        ObjectKind::Aggregate => ObjectKind::Routine,
        // No `GRANT … ON INDEX` or `ON EXTENSION` exists.
        ObjectKind::Index | ObjectKind::Extension => return Err(unsupported(op, ctx)),
        k => k,
    };
    if g.privileges.is_empty() {
        return Err(RenderError::Invalid("a grant without privileges"));
    }
    let cols = if g.columns.is_empty() {
        String::new()
    } else {
        format!(" {}", ctx.ident_list(&g.columns)?)
    };
    let privs: Result<Vec<String>, RenderError> = g
        .privileges
        .iter()
        .map(|p| Ok(format!("{}{cols}", privilege(p)?)))
        .collect();
    // `PUBLIC` is the keyword (an empty aclitem grantee), never a role name.
    let grantee = if &*g.grantee == "PUBLIC" {
        "PUBLIC".to_string()
    } else {
        // ## m4-t33a-hygiene (named exception): `public` and `none` are refused.
        role(ctx, &g.grantee)?
    };
    let on = object_ref(ctx, op, kind, &g.object, g.sig.as_deref())?;
    let mut s = format!("GRANT {} ON {on} TO {grantee}", privs?.join(", "));
    if g.grantable {
        s.push_str(" WITH GRANT OPTION");
    }
    Ok(stmt(s, TX))
}
