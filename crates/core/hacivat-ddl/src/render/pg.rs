//! The PostgreSQL renderer (14–18; PG-wire dialects use it too).

use hacivat_meta::{Name, ObjectKind};

use super::{
    RenderCtx, Renderer, Stmt, TxnClass, deferrable_tail, fk_tail, index_part, routine_ref, stmt,
    trim_server_text, unsupported,
};
use crate::error::RenderError;
use crate::ir::*;

pub struct PgRenderer;

const TX: TxnClass = TxnClass::Transactional;

impl Renderer for PgRenderer {
    fn render(&self, op: &DdlOp, ctx: &RenderCtx<'_>) -> Result<Vec<Stmt>, RenderError> {
        match op {
            DdlOp::CreateSchema(s) => schema(ctx, s),
            DdlOp::CreateTable(t) => table(ctx, t),
            DdlOp::AlterTable { table, actions } => alter_table(ctx, op, table, actions),
            DdlOp::CreateIndex(i) => index(ctx, i),
            DdlOp::CreateView(v) => view(ctx, v),
            DdlOp::CreateRoutine(r) => routine(ctx, r),
            DdlOp::CreateTrigger(t) => trigger(ctx, t),
            DdlOp::CreateSequence(s) => sequence(ctx, s),
            DdlOp::AlterSequence { name, actions } => alter_sequence(ctx, name, actions),
            DdlOp::CreateType(t) => type_def(ctx, t),
            DdlOp::Comment { target, text } => Ok(vec![comment(ctx, target, text.as_deref())?]),
            DdlOp::Grant(g) => Ok(vec![grant(ctx, op, g)?]),
            DdlOp::Owner {
                kind,
                name,
                sig,
                owner,
            } => Ok(vec![owner_stmt(ctx, op, *kind, name, sig.as_ref(), owner)?]),
            DdlOp::Raw {
                sql,
                origin: RawOrigin::ServerText,
            } => Ok(vec![stmt(trim_server_text(sql).to_string(), TX)]),
            _ => Err(unsupported(op, ctx.dialect())),
        }
    }
}

fn schema(ctx: &RenderCtx<'_>, s: &SchemaDef) -> Result<Vec<Stmt>, RenderError> {
    let ine = if s.if_not_exists {
        "IF NOT EXISTS "
    } else {
        ""
    };
    let mut out = vec![stmt(
        format!("CREATE SCHEMA {ine}{}", ctx.ident(&s.name)),
        TX,
    )];
    if let Some(c) = &s.comment {
        out.push(comment(
            ctx,
            &CommentTarget {
                kind: ObjectKind::Schema,
                name: QName::bare(&s.name),
                column: None,
                sig: None,
                on: None,
            },
            Some(c),
        )?);
    }
    Ok(out)
}

/// One column definition with its inline constraints.
fn column(
    ctx: &RenderCtx<'_>,
    c: &ColumnDef,
    inline: &[&ConstraintDef],
) -> Result<String, RenderError> {
    let mut s = format!("{} {}", ctx.ident(&c.name), c.type_text);
    if let Some(coll) = &c.collation {
        s.push_str(" COLLATE ");
        s.push_str(&ctx.ident(coll));
    }
    if let Some(g) = &c.generated {
        s.push_str(&format!(
            " GENERATED ALWAYS AS ({}) {}",
            g.expr,
            if g.stored { "STORED" } else { "VIRTUAL" }
        ));
    } else {
        match c.identity {
            Some(IdentityDef::Always) => s.push_str(" GENERATED ALWAYS AS IDENTITY"),
            Some(IdentityDef::ByDefault) => s.push_str(" GENERATED BY DEFAULT AS IDENTITY"),
            Some(IdentityDef::AutoIncrement) => {
                return Err(RenderError::Invalid("AUTO_INCREMENT on PostgreSQL"));
            }
            None => {
                if let Some(d) = &c.default {
                    s.push_str(" DEFAULT ");
                    s.push_str(d);
                }
            }
        }
    }
    if !c.nullable {
        s.push_str(" NOT NULL");
    }
    for k in inline {
        s.push(' ');
        s.push_str(&constraint(ctx, k, true)?);
    }
    Ok(s)
}

/// A constraint as a table element (`inline = false`) or inside its column.
pub(crate) fn constraint(
    ctx: &RenderCtx<'_>,
    k: &ConstraintDef,
    inline: bool,
) -> Result<String, RenderError> {
    let mut s = String::new();
    if let Some(n) = &k.name {
        s.push_str("CONSTRAINT ");
        s.push_str(&ctx.ident(n));
        s.push(' ');
    }
    match &k.body {
        ConstraintBody::PrimaryKey { columns } => {
            s.push_str("PRIMARY KEY");
            if !inline {
                s.push(' ');
                s.push_str(&ctx.ident_list(columns));
            }
        }
        ConstraintBody::Unique { columns } => {
            s.push_str("UNIQUE");
            if !inline {
                s.push(' ');
                s.push_str(&ctx.ident_list(columns));
            }
        }
        ConstraintBody::ForeignKey {
            columns,
            target,
            target_columns,
            on_update,
            on_delete,
            match_kind,
        } => {
            if !inline {
                s.push_str("FOREIGN KEY ");
                s.push_str(&ctx.ident_list(columns));
                s.push(' ');
            }
            s.push_str("REFERENCES ");
            s.push_str(&ctx.qname(target));
            if !target_columns.is_empty() {
                s.push(' ');
                s.push_str(&ctx.ident_list(target_columns));
            }
            s.push_str(&fk_tail(*match_kind, *on_update, *on_delete));
        }
        ConstraintBody::Check { expr } => {
            s.push_str(&format!("CHECK ({expr})"));
        }
        ConstraintBody::Exclusion { def } => {
            if inline {
                return Err(RenderError::Invalid("EXCLUDE inside a column"));
            }
            s.push_str("EXCLUDE ");
            s.push_str(def);
        }
    }
    s.push_str(deferrable_tail(k.deferrable));
    Ok(s)
}

fn elements(ctx: &RenderCtx<'_>, t: &TableDef) -> Result<Vec<String>, RenderError> {
    let mut out = Vec::new();
    for c in &t.columns {
        let inline: Vec<&ConstraintDef> = t
            .constraints
            .iter()
            .filter(|k| matches!(&k.position, Position::InColumn(n) if *n == c.name))
            .collect();
        out.push(column(ctx, c, &inline)?);
    }
    for k in &t.constraints {
        if k.position == Position::InTable {
            out.push(constraint(ctx, k, false)?);
        }
    }
    Ok(out)
}

fn element_block(items: &[String]) -> String {
    if items.is_empty() {
        return "()".to_string();
    }
    let mut s = String::from("(\n");
    for (i, e) in items.iter().enumerate() {
        s.push_str("    ");
        s.push_str(e);
        if i + 1 < items.len() {
            s.push(',');
        }
        s.push('\n');
    }
    s.push(')');
    s
}

fn table(ctx: &RenderCtx<'_>, t: &TableDef) -> Result<Vec<Stmt>, RenderError> {
    let ext = match &t.ext {
        TableDefExt::Pg(p) => p.clone(),
        TableDefExt::None => PgTableDef::default(),
        _ => return Err(RenderError::Invalid("non-PostgreSQL table clauses")),
    };
    let mut head = String::from("CREATE ");
    if ext.temporary {
        head.push_str("TEMPORARY ");
    } else if ext.unlogged {
        head.push_str("UNLOGGED ");
    }
    head.push_str("TABLE ");
    if t.if_not_exists {
        head.push_str("IF NOT EXISTS ");
    }
    head.push_str(&ctx.qname(&t.name));
    let items = elements(ctx, t)?;
    let mut s = head;
    if let Some((parent, bound)) = &ext.partition_of {
        s.push_str(" PARTITION OF ");
        s.push_str(&ctx.qname(parent));
        if !items.is_empty() {
            s.push(' ');
            s.push_str(&element_block(&items));
        }
        s.push(' ');
        s.push_str(bound);
    } else {
        s.push(' ');
        s.push_str(&element_block(&items));
        if !ext.inherits.is_empty() {
            let parents: Vec<String> = ext.inherits.iter().map(|p| ctx.qname(p)).collect();
            s.push_str(&format!("\nINHERITS ({})", parents.join(", ")));
        }
    }
    if let Some(p) = &ext.partition_by {
        s.push_str("\nPARTITION BY ");
        s.push_str(p);
    }
    if let Some(am) = &ext.access_method
        && !am.eq_ignore_ascii_case("heap")
    {
        s.push_str("\nUSING ");
        s.push_str(&ctx.ident(am));
    }
    if !ext.with.is_empty() {
        s.push_str(&format!("\nWITH ({})", ext.with.join(", ")));
    }
    if let Some(ts) = &ext.tablespace {
        s.push_str("\nTABLESPACE ");
        s.push_str(&ctx.ident(ts));
    }
    let mut out = vec![stmt(s, TX)];
    for i in &t.indexes {
        out.extend(index(ctx, i)?);
    }
    let target = |kind, column: Option<&Name>| CommentTarget {
        kind,
        name: t.name.clone(),
        column: column.cloned(),
        sig: None,
        on: None,
    };
    if let Some(c) = &t.comment {
        out.push(comment(ctx, &target(ObjectKind::Table, None), Some(c))?);
    }
    for c in &t.columns {
        if let Some(text) = &c.comment {
            out.push(comment(
                ctx,
                &target(ObjectKind::Column, Some(&c.name)),
                Some(text),
            )?);
        }
    }
    Ok(out)
}

fn alter_table(
    ctx: &RenderCtx<'_>,
    op: &DdlOp,
    table: &QName,
    actions: &[AlterAction],
) -> Result<Vec<Stmt>, RenderError> {
    let mut out = Vec::new();
    for a in actions {
        match a {
            AlterAction::AddConstraint(k) => {
                let mut s = format!(
                    "ALTER TABLE {} ADD {}",
                    ctx.qname(table),
                    constraint(ctx, k, false)?
                );
                if k.not_valid {
                    s.push_str(" NOT VALID");
                }
                out.push(stmt(s, TX));
            }
            _ => return Err(unsupported(op, ctx.dialect())),
        }
    }
    Ok(out)
}

fn index(ctx: &RenderCtx<'_>, i: &IndexDef) -> Result<Vec<Stmt>, RenderError> {
    let mut s = String::from("CREATE ");
    if i.unique {
        s.push_str("UNIQUE ");
    }
    s.push_str("INDEX ");
    if i.if_not_exists {
        s.push_str("IF NOT EXISTS ");
    }
    s.push_str(&ctx.ident(&i.name));
    s.push_str(" ON ");
    s.push_str(&ctx.qname(&i.table));
    if let Some(m) = &i.method
        && !m.eq_ignore_ascii_case("btree")
    {
        s.push_str(" USING ");
        s.push_str(&ctx.ident(m));
    }
    let parts: Result<Vec<String>, _> = i.parts.iter().map(|p| index_part(ctx, p)).collect();
    s.push_str(&format!(" ({})", parts?.join(", ")));
    if !i.include.is_empty() {
        s.push_str(" INCLUDE ");
        s.push_str(&ctx.ident_list(&i.include));
    }
    if let Some(p) = &i.predicate {
        s.push_str(" WHERE ");
        s.push_str(p);
    }
    let mut out = vec![stmt(s, TX)];
    if let Some(c) = &i.comment {
        out.push(comment(
            ctx,
            &CommentTarget {
                kind: ObjectKind::Index,
                name: QName {
                    schema: i.table.schema.clone(),
                    name: i.name.clone(),
                },
                column: None,
                sig: None,
                on: None,
            },
            Some(c),
        )?);
    }
    Ok(out)
}

fn view(ctx: &RenderCtx<'_>, v: &ViewDef) -> Result<Vec<Stmt>, RenderError> {
    let kind = match v.kind {
        ViewKind::View => ObjectKind::View,
        ViewKind::Materialized => ObjectKind::MaterializedView,
    };
    let text = match &v.body {
        ViewBody::Query(q) => {
            let mut s = String::from("CREATE ");
            match v.kind {
                ViewKind::View if v.or_replace => s.push_str("OR REPLACE VIEW "),
                ViewKind::View => s.push_str("VIEW "),
                ViewKind::Materialized => s.push_str("MATERIALIZED VIEW "),
            }
            s.push_str(&ctx.qname(&v.name));
            s.push_str(" AS\n");
            s.push_str(trim_server_text(q));
            if let Some(opt) = &v.check_option {
                s.push_str(&format!("\n  WITH {opt} CHECK OPTION"));
            }
            s
        }
        ViewBody::ServerText(t) => trim_server_text(t).to_string(),
    };
    let mut out = vec![stmt(text, TX)];
    if let Some(c) = &v.comment {
        out.push(comment(
            ctx,
            &CommentTarget {
                kind,
                name: v.name.clone(),
                column: None,
                sig: None,
                on: None,
            },
            Some(c),
        )?);
    }
    for (col, text) in &v.column_comments {
        out.push(comment(
            ctx,
            &CommentTarget {
                kind: ObjectKind::Column,
                name: v.name.clone(),
                column: Some(col.clone()),
                sig: None,
                on: None,
            },
            Some(text),
        )?);
    }
    Ok(out)
}

fn routine(ctx: &RenderCtx<'_>, r: &RoutineDef) -> Result<Vec<Stmt>, RenderError> {
    let mut out = vec![stmt(trim_server_text(&r.text).to_string(), TX)];
    if let Some(c) = &r.comment {
        out.push(comment(
            ctx,
            &CommentTarget {
                kind: r.kind,
                name: r.name.clone(),
                column: None,
                sig: Some(r.sig.clone().unwrap_or_else(|| Name::from(""))),
                on: None,
            },
            Some(c),
        )?);
    }
    Ok(out)
}

fn trigger(ctx: &RenderCtx<'_>, t: &TriggerDef) -> Result<Vec<Stmt>, RenderError> {
    let mut out = vec![stmt(trim_server_text(&t.text).to_string(), TX)];
    if let Some(c) = &t.comment {
        out.push(comment(
            ctx,
            &CommentTarget {
                kind: ObjectKind::Trigger,
                name: QName::bare(&t.name),
                column: None,
                sig: None,
                on: Some(t.table.clone()),
            },
            Some(c),
        )?);
    }
    Ok(out)
}

/// `(min, max)` of a PostgreSQL sequence type; `bigint` for anything else.
fn seq_bounds(ty: Option<&str>) -> (i64, i64) {
    match ty {
        Some(t) if t.eq_ignore_ascii_case("smallint") => (i64::from(i16::MIN), i64::from(i16::MAX)),
        Some(t) if t.eq_ignore_ascii_case("integer") => (i64::from(i32::MIN), i64::from(i32::MAX)),
        _ => (i64::MIN, i64::MAX),
    }
}

/// The clauses of a sequence that differ from the server's defaults, PostgreSQL rules
/// (`CREATE SEQUENCE` docs): increment 1; ascending min 1 and max the type's maximum;
/// descending min the type's minimum and max -1; start at min (ascending) or max
/// (descending); cache 1.
fn sequence(ctx: &RenderCtx<'_>, q: &SeqDef) -> Result<Vec<Stmt>, RenderError> {
    let ty = q.data_type.as_deref();
    let (tmin, tmax) = seq_bounds(ty);
    let inc = q.increment.unwrap_or(1);
    let asc = inc > 0;
    let dmin = if asc { 1 } else { tmin };
    let dmax = if asc { tmax } else { -1 };
    let min = q.min.unwrap_or(dmin);
    let max = q.max.unwrap_or(dmax);
    let dstart = if asc { min } else { max };
    let mut clauses = Vec::new();
    if let Some(t) = ty
        && !t.eq_ignore_ascii_case("bigint")
    {
        clauses.push(format!("AS {t}"));
    }
    if inc != 1 {
        clauses.push(format!("INCREMENT BY {inc}"));
    }
    if min != dmin {
        clauses.push(format!("MINVALUE {min}"));
    }
    if max != dmax {
        clauses.push(format!("MAXVALUE {max}"));
    }
    if let Some(s) = q.start
        && s != dstart
    {
        clauses.push(format!("START WITH {s}"));
    }
    if let Some(c) = q.cache
        && c != 1
    {
        clauses.push(format!("CACHE {c}"));
    }
    if q.cycle {
        clauses.push("CYCLE".to_string());
    }
    let ine = if q.if_not_exists {
        "IF NOT EXISTS "
    } else {
        ""
    };
    let mut s = format!("CREATE SEQUENCE {ine}{}", ctx.qname(&q.name));
    for c in clauses {
        s.push_str("\n    ");
        s.push_str(&c);
    }
    let mut out = vec![stmt(s, TX)];
    if let Some(c) = &q.comment {
        out.push(comment(
            ctx,
            &CommentTarget {
                kind: ObjectKind::Sequence,
                name: q.name.clone(),
                column: None,
                sig: None,
                on: None,
            },
            Some(c),
        )?);
    }
    Ok(out)
}

fn alter_sequence(
    ctx: &RenderCtx<'_>,
    name: &QName,
    actions: &[SeqAction],
) -> Result<Vec<Stmt>, RenderError> {
    let mut out = Vec::new();
    for a in actions {
        match a {
            SeqAction::OwnedBy(Some((table, col))) => out.push(stmt(
                format!(
                    "ALTER SEQUENCE {} OWNED BY {}.{}",
                    ctx.qname(name),
                    ctx.qname(table),
                    ctx.ident(col)
                ),
                TX,
            )),
            SeqAction::OwnedBy(None) => out.push(stmt(
                format!("ALTER SEQUENCE {} OWNED BY NONE", ctx.qname(name)),
                TX,
            )),
        }
    }
    Ok(out)
}

fn type_def(ctx: &RenderCtx<'_>, t: &TypeDef) -> Result<Vec<Stmt>, RenderError> {
    let name = ctx.qname(&t.name);
    let (text, kind) = match &t.body {
        TypeBody::Enum { labels } => {
            let mut lits = Vec::new();
            for l in labels {
                lits.push(ctx.literal(l, "enum label")?);
            }
            let body = if lits.is_empty() {
                "()".to_string()
            } else {
                format!("(\n    {}\n)", lits.join(",\n    "))
            };
            (
                format!("CREATE TYPE {name} AS ENUM {body}"),
                ObjectKind::EnumType,
            )
        }
        TypeBody::Domain {
            base,
            collation,
            default,
            not_null,
            checks,
        } => {
            let mut s = format!("CREATE DOMAIN {name} AS {base}");
            if let Some(c) = collation {
                s.push_str(" COLLATE ");
                s.push_str(&ctx.ident(c));
            }
            if let Some(d) = default {
                s.push_str(" DEFAULT ");
                s.push_str(d);
            }
            if *not_null {
                s.push_str(" NOT NULL");
            }
            for (cn, expr) in checks {
                s.push_str("\n    ");
                if let Some(cn) = cn {
                    s.push_str(&format!("CONSTRAINT {} ", ctx.ident(cn)));
                }
                s.push_str(&format!("CHECK ({expr})"));
            }
            (s, ObjectKind::Domain)
        }
        TypeBody::Composite { attrs } => {
            let items: Vec<String> = attrs
                .iter()
                .map(|(n, ty, coll)| {
                    let mut s = format!("{} {ty}", ctx.ident(n));
                    if let Some(c) = coll {
                        s.push_str(" COLLATE ");
                        s.push_str(&ctx.ident(c));
                    }
                    s
                })
                .collect();
            (
                format!("CREATE TYPE {name} AS {}", element_block(&items)),
                ObjectKind::CompositeType,
            )
        }
        TypeBody::Range { subtype } => (
            format!("CREATE TYPE {name} AS RANGE (\n    subtype = {subtype}\n)"),
            ObjectKind::RangeType,
        ),
    };
    let mut out = vec![stmt(text, TX)];
    if let Some(c) = &t.comment {
        out.push(comment(
            ctx,
            &CommentTarget {
                kind,
                name: t.name.clone(),
                column: None,
                sig: None,
                on: None,
            },
            Some(c),
        )?);
    }
    Ok(out)
}

/// The object-type words of `COMMENT ON`, `ALTER … OWNER TO` and `GRANT … ON`.
fn kind_word(kind: ObjectKind) -> Option<&'static str> {
    use ObjectKind::*;
    Some(match kind {
        Schema => "SCHEMA",
        Database => "DATABASE",
        Table | Partition => "TABLE",
        View => "VIEW",
        MaterializedView => "MATERIALIZED VIEW",
        ForeignTable => "FOREIGN TABLE",
        Index => "INDEX",
        Sequence => "SEQUENCE",
        Routine => "FUNCTION",
        Procedure => "PROCEDURE",
        Aggregate => "AGGREGATE",
        Domain => "DOMAIN",
        EnumType | CompositeType | RangeType => "TYPE",
        Extension => "EXTENSION",
        _ => return None,
    })
}

fn is_routine(kind: ObjectKind) -> bool {
    matches!(
        kind,
        ObjectKind::Routine | ObjectKind::Procedure | ObjectKind::Aggregate
    )
}

/// `COMMENT ON … IS '…'` (`IS NULL` removes the comment).
pub(crate) fn comment(
    ctx: &RenderCtx<'_>,
    t: &CommentTarget,
    text: Option<&str>,
) -> Result<Stmt, RenderError> {
    use ObjectKind::*;
    let what = match t.kind {
        Column => {
            let col = t
                .column
                .as_ref()
                .ok_or(RenderError::Invalid("column comment without a column"))?;
            format!("COLUMN {}.{}", ctx.qname(&t.name), ctx.ident(col))
        }
        Trigger | PrimaryKey | UniqueKey | ForeignKey | Check | Exclusion | Policy | Rule => {
            let on =
                t.on.as_ref()
                    .ok_or(RenderError::Invalid("comment without its table"))?;
            let word = match t.kind {
                Trigger => "TRIGGER",
                Policy => "POLICY",
                Rule => "RULE",
                _ => "CONSTRAINT",
            };
            format!("{word} {} ON {}", ctx.ident(&t.name.name), ctx.qname(on))
        }
        k if is_routine(k) => format!(
            "{} {}",
            kind_word(k).unwrap_or("FUNCTION"),
            routine_ref(ctx, &t.name, t.sig.as_ref())
        ),
        k => {
            let word = kind_word(k).ok_or(RenderError::Unsupported {
                op: "Comment",
                dialect: ctx.dialect(),
            })?;
            format!("{word} {}", ctx.qname(&t.name))
        }
    };
    let lit = match text {
        Some(s) => ctx.literal(s, "comment")?,
        None => "NULL".to_string(),
    };
    Ok(stmt(format!("COMMENT ON {what} IS {lit}"), TX))
}

fn object_ref(
    ctx: &RenderCtx<'_>,
    op: &DdlOp,
    kind: ObjectKind,
    name: &QName,
    sig: Option<&Name>,
) -> Result<String, RenderError> {
    let word = kind_word(kind).ok_or_else(|| unsupported(op, ctx.dialect()))?;
    Ok(if is_routine(kind) {
        format!("{word} {}", routine_ref(ctx, name, sig))
    } else {
        format!("{word} {}", ctx.qname(name))
    })
}

fn owner_stmt(
    ctx: &RenderCtx<'_>,
    op: &DdlOp,
    kind: ObjectKind,
    name: &QName,
    sig: Option<&Name>,
    owner: &str,
) -> Result<Stmt, RenderError> {
    if kind == ObjectKind::Index {
        return Err(unsupported(op, ctx.dialect()));
    }
    Ok(stmt(
        format!(
            "ALTER {} OWNER TO {}",
            object_ref(ctx, op, kind, name, sig)?,
            ctx.ident(owner)
        ),
        TX,
    ))
}

fn grant(ctx: &RenderCtx<'_>, op: &DdlOp, g: &GrantDef) -> Result<Stmt, RenderError> {
    // Views, materialized views and foreign tables are granted `ON TABLE` too.
    let kind = match g.kind {
        ObjectKind::View | ObjectKind::MaterializedView | ObjectKind::ForeignTable => {
            ObjectKind::Table
        }
        k => k,
    };
    if g.privileges.is_empty() {
        return Err(RenderError::Invalid("grant without privileges"));
    }
    let cols = if g.columns.is_empty() {
        String::new()
    } else {
        format!(" {}", ctx.ident_list(&g.columns))
    };
    let privs: Vec<String> = g.privileges.iter().map(|p| format!("{p}{cols}")).collect();
    let grantee = if &*g.grantee == "PUBLIC" {
        "PUBLIC".to_string()
    } else {
        ctx.ident(&g.grantee)
    };
    let word_ref = object_ref(ctx, op, kind, &g.object, g.sig.as_ref())?;
    let mut s = format!("GRANT {} ON {word_ref} TO {grantee}", privs.join(", "));
    if g.with_grant_option {
        s.push_str(" WITH GRANT OPTION");
    }
    Ok(stmt(s, TX))
}
