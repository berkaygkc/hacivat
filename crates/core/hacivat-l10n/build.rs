//! Generates `ids.rs` (I18N-04 step 1): one `MsgRef` constant per English message, grouped by
//! ID prefix (`hacivat_l10n::ids::{cm, hv, hui, ..}`), plus an arguments struct for every
//! message with variables. An undocumented variable fails the build.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use hacivat_l10n_schema::{Signature, VarType, extract};

/// Modules that always exist, even before they hold a message.
const ALWAYS: [&str; 3] = ["cm", "hv", "hui"];

fn main() {
    println!("cargo:rerun-if-changed=../../../locales");
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let en = Path::new(&manifest_dir).join("../../../locales/en");

    let mut files: Vec<_> = std::fs::read_dir(&en)
        .unwrap_or_else(|e| fail(&[format!("cannot read {}: {e}", en.display())]))
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|x| x == "ftl"))
        .collect();
    files.sort();

    let mut errors = Vec::new();
    let mut sigs: Vec<(String, Signature)> = Vec::new();
    for path in &files {
        let name = format!(
            "en/{}",
            path.file_name().unwrap_or_default().to_string_lossy()
        );
        let src = std::fs::read_to_string(path)
            .unwrap_or_else(|e| fail(&[format!("cannot read {name}: {e}")]));
        match extract(&src, &name) {
            Ok(found) => {
                for sig in found {
                    if let Some((other, _)) = sigs.iter().find(|(_, s)| s.id == sig.id) {
                        errors.push(format!("{name}: `{}` is also defined in {other}", sig.id));
                    } else {
                        sigs.push((name.clone(), sig));
                    }
                }
            }
            Err(errs) => errors.extend(errs.iter().map(ToString::to_string)),
        }
    }
    if !errors.is_empty() {
        fail(&errors);
    }

    let code = generate(sigs.into_iter().map(|(_, s)| s).collect()).unwrap_or_else(|e| fail(&e));
    let out = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("ids.rs");
    std::fs::write(&out, code).unwrap_or_else(|e| fail(&[format!("cannot write ids.rs: {e}")]));
}

fn fail(errors: &[String]) -> ! {
    for e in errors {
        eprintln!("error: {e}");
    }
    eprintln!(
        "error: locales/en has {} catalog error(s); see above",
        errors.len()
    );
    std::process::exit(1);
}

fn generate(sigs: Vec<Signature>) -> Result<String, Vec<String>> {
    let mut modules: BTreeMap<String, Vec<Signature>> =
        ALWAYS.iter().map(|m| (m.to_string(), Vec::new())).collect();
    for sig in sigs {
        let prefix = sig.id.split('-').next().unwrap_or_default().to_string();
        modules.entry(prefix).or_default().push(sig);
    }

    let mut errors = Vec::new();
    let mut out = String::from("// @generated by hacivat-l10n/build.rs from locales/en/*.ftl.\n");
    for (module, sigs) in &modules {
        let mut names = Names::new(module);
        writeln!(out, "\n/// Messages with the `{module}-` prefix.").unwrap();
        writeln!(out, "pub mod {module} {{").unwrap();
        for sig in sigs {
            message(&mut out, sig, &mut names, &mut errors);
        }
        out.push_str("}\n");
    }
    if errors.is_empty() {
        Ok(out)
    } else {
        Err(errors)
    }
}

/// The generated names of one `ids` module, so two IDs (or two variables, or two enum values)
/// that map to the same Rust name fail the build instead of generating code that does not
/// compile (`hv-x` with `$kind (Enum(..))` and `hv-x-kind` both want `HvXKind`).
struct Names {
    module: String,
    /// Constants live in the value namespace.
    values: BTreeMap<String, String>,
    /// Argument structs and enums live in the type namespace.
    types: BTreeMap<String, String>,
}

impl Names {
    fn new(module: &str) -> Names {
        Names {
            module: module.to_string(),
            values: BTreeMap::new(),
            types: BTreeMap::new(),
        }
    }

    fn value(&mut self, name: &str, origin: &str, errors: &mut Vec<String>) {
        claim(
            &mut self.values,
            name,
            origin,
            &format!("`ids::{}`", self.module),
            errors,
        );
    }

    fn ty(&mut self, name: &str, origin: &str, errors: &mut Vec<String>) {
        claim(
            &mut self.types,
            name,
            origin,
            &format!("`ids::{}`", self.module),
            errors,
        );
    }
}

/// Records that `origin` generates `name` in `scope`, or reports the clash.
fn claim(
    seen: &mut BTreeMap<String, String>,
    name: &str,
    origin: &str,
    scope: &str,
    errors: &mut Vec<String>,
) {
    if let Some(other) = seen.get(name) {
        errors.push(format!(
            "{other} and {origin} both generate the name `{name}` in {scope}; rename one of them"
        ));
    } else {
        seen.insert(name.to_string(), origin.to_string());
    }
}

fn message(out: &mut String, sig: &Signature, names: &mut Names, errors: &mut Vec<String>) {
    let id = &sig.id;
    let rest = id.split_once('-').map_or(id.as_str(), |(_, r)| r);
    let mut konst = rest.replace('-', "_").to_ascii_uppercase();
    if konst.starts_with(|c: char| c.is_ascii_digit()) {
        konst.insert(0, '_');
    }
    names.value(&konst, &format!("`{id}`"), errors);
    let attrs = if sig.attrs.is_empty() {
        String::new()
    } else {
        format!(
            " Attributes: {}.",
            sig.attrs
                .iter()
                .map(|a| format!("`.{a}`"))
                .collect::<Vec<_>>()
                .join(", ")
        )
    };

    if sig.vars.is_empty() {
        writeln!(out, "    /// `{id}`.{attrs}").unwrap();
        writeln!(
            out,
            "    pub const {konst}: crate::args::MsgRef<crate::args::NoArgs> = crate::args::MsgRef::new(\"{id}\");"
        )
        .unwrap();
        return;
    }

    let strukt = pascal(id);
    names.ty(&strukt, &format!("`{id}`"), errors);
    writeln!(out, "    /// `{id}`.{attrs}").unwrap();
    writeln!(
        out,
        "    pub const {konst}: crate::args::MsgRef<{strukt}> = crate::args::MsgRef::new(\"{id}\");"
    )
    .unwrap();

    let mut fields = String::new();
    let mut conversions = String::new();
    let mut enums = String::new();
    let mut field_names = BTreeMap::new();
    for (var, ty) in &sig.vars {
        let field = field_name(var);
        claim(
            &mut field_names,
            &field,
            &format!("`${var}`"),
            &format!("the arguments of `{id}`"),
            errors,
        );
        let rust_ty = match ty {
            VarType::String => "crate::args::Text".to_string(),
            VarType::Number => "crate::args::Count".to_string(),
            VarType::Decimal => "crate::args::ExactDecimal".to_string(),
            VarType::DateTime => "crate::args::WhenValue".to_string(),
            VarType::List => "::std::vec::Vec<::std::string::String>".to_string(),
            VarType::Enum(values) => {
                let name = format!("{strukt}{}", pascal(var));
                names.ty(&name, &format!("`{id}` `${var}`"), errors);
                enum_type(&mut enums, &name, id, var, values, errors);
                name
            }
        };
        writeln!(fields, "        /// `${var}`").unwrap();
        writeln!(fields, "        pub {field}: {rust_ty},").unwrap();
        writeln!(conversions, "            (\"{var}\", self.{field}.into()),").unwrap();
    }

    writeln!(out, "    /// The arguments of `{id}`.").unwrap();
    writeln!(out, "    #[allow(non_snake_case)]").unwrap();
    writeln!(out, "    #[derive(Debug, Clone, PartialEq, Eq, Hash)]").unwrap();
    writeln!(out, "    pub struct {strukt} {{\n{fields}    }}").unwrap();
    writeln!(out, "    impl crate::args::IntoFluentArgs for {strukt} {{").unwrap();
    writeln!(
        out,
        "        fn into_args(self) -> ::std::vec::Vec<(&'static str, crate::args::ArgValue)> {{\n            ::std::vec![\n{conversions}            ]\n        }}\n    }}"
    )
    .unwrap();
    out.push_str(&enums);
}

fn enum_type(
    out: &mut String,
    name: &str,
    id: &str,
    var: &str,
    values: &[String],
    errors: &mut Vec<String>,
) {
    let mut variants = String::new();
    let mut arms = String::new();
    let mut seen = BTreeMap::new();
    for value in values {
        let variant = pascal(value);
        if !variant.starts_with(|c: char| c.is_ascii_alphabetic())
            || !variant.chars().all(|c| c.is_ascii_alphanumeric())
        {
            errors.push(format!(
                "`{id}`: `${var}` enum value `{value}` must be ASCII letters, digits, `-` or `_`"
            ));
            continue;
        }
        claim(
            &mut seen,
            &variant,
            &format!("value `{value}`"),
            &format!("the `${var}` values of `{id}`"),
            errors,
        );
        writeln!(variants, "        {variant},").unwrap();
        writeln!(arms, "                {name}::{variant} => \"{value}\",").unwrap();
    }
    writeln!(out, "    /// The values of `${var}` in `{id}`.").unwrap();
    writeln!(
        out,
        "    #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]"
    )
    .unwrap();
    writeln!(out, "    pub enum {name} {{\n{variants}    }}").unwrap();
    writeln!(
        out,
        "    impl ::std::convert::From<{name}> for crate::args::ArgValue {{"
    )
    .unwrap();
    writeln!(
        out,
        "        fn from(v: {name}) -> Self {{\n            crate::args::ArgValue::Text(::std::string::String::from(match v {{\n{arms}            }}))\n        }}\n    }}"
    )
    .unwrap();
}

/// `hv-tab-console-untitled` → `HvTabConsoleUntitled`.
fn pascal(s: &str) -> String {
    s.split(['-', '_', ' '])
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut cs = p.chars();
            cs.next().map_or_else(String::new, |first| {
                let mut w = first.to_ascii_uppercase().to_string();
                w.extend(cs);
                w
            })
        })
        .collect()
}

/// A Fluent variable name as a Rust field name.
fn field_name(var: &str) -> String {
    const RAW: [&str; 35] = [
        "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern",
        "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut",
        "pub", "ref", "return", "static", "struct", "trait", "true", "type", "unsafe", "use",
        "where", "while", "gen",
    ];
    let name = var.replace('-', "_");
    if ["self", "Self", "super", "crate"].contains(&name.as_str()) {
        format!("{name}_")
    } else if RAW.contains(&name.as_str()) {
        format!("r#{name}")
    } else {
        name
    }
}
