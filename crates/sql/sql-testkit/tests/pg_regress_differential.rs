//! The PostgreSQL regression differential (Task 20; SQL-T13; the P0 exit, `alg/10` :171): our
//! PG split equals libpg_query's on at least 99.9 % of the regression corpus's comparable
//! statements (`sql_testkit::differential` says how they are compared); every disagreement is
//! listed, and the statements the rate leaves out (uncertain, not comparable) are pinned in
//! checked-in listings (fix round 1, I2). The patched one-parse oracle's byte-identity on the
//! same corpus is `sql-safety`'s `tests/oracle_corpus.rs` (the layering rule keeps
//! `sql_oracle_pg::tree` inside its owners).
//!
//! Needs the corpus: `cargo xtask fetch-pg-regress --tag REL_17_2` (network once; pinned by
//! digest, and re-checked here). It runs with the `differential` feature (T1a R1-M2: the plain
//! test loops never build libpg_query through this crate), in the nightly `sql-differential`
//! job and at the gate:
//!
//! ```text
//! cargo test -p sql-testkit --features differential --test pg_regress_differential -- --ignored
//! ```
//!
//! `HACIVAT_DIFFERENTIAL_WRITE=1` rewrites the two listings (after a reviewed splitter change)
//! and prints the corpus digest. Without the feature this file compiles to nothing.

#[cfg(feature = "differential")]
mod differential {
    use sql_testkit::differential::{
        CORPUS_FNV, TAG, check_listing, compare_files, corpus_digest, corpus_dir, corpus_files,
        listing, listing_path,
    };

    /// The listings' tolerance on the count: ±1 % (a statement that moves into a bucket fails
    /// whatever the count).
    const TOLERANCE: f64 = 0.01;

    fn files() -> Vec<(String, Vec<u8>)> {
        let dir = corpus_dir(TAG);
        let Some(files) = corpus_files(&dir) else {
            panic!(
                "no corpus at {}: run `cargo xtask fetch-pg-regress --tag {TAG}` first",
                dir.display()
            );
        };
        let digest = corpus_digest(&files);
        if std::env::var("HACIVAT_DIFFERENTIAL_WRITE").as_deref() == Ok("1") {
            eprintln!("corpus FNV-1a 64: {digest:#018x}");
        } else {
            assert_eq!(
                digest,
                CORPUS_FNV,
                "the corpus at {} is not REL_17_2's pinned files (edited locally?): fetch it again",
                dir.display()
            );
        }
        files
    }

    #[test]
    #[ignore = "network"]
    fn pg_regress_split_agrees_at_least_999_per_mille() {
        let o = compare_files(&files());
        eprintln!(
            "pg_regress {TAG}: {} files, {} statements: {} agree, {} disagree, {} not comparable \
             (syntax errors), {} uncertain (refused); {:.2} per mille of the comparable, {:.2} \
             per mille of all; unreadable: {:?}",
            o.files,
            o.statements,
            o.agreed,
            o.disagreed.len(),
            o.not_comparable.len(),
            o.uncertain.len(),
            o.per_mille(),
            o.per_mille_of_all(),
            o.unreadable
        );
        for d in &o.disagreed {
            eprintln!("  disagree {} {:?}: {:?}", d.file, d.range, d.head);
        }
        let buckets = [
            (
                "uncertain",
                format!("{TAG}-uncertain.tsv"),
                &o.uncertain,
                "statements our PG split leaves uncertain (Run refuses them)",
            ),
            (
                "not comparable",
                format!("{TAG}-not-comparable.tsv"),
                &o.not_comparable,
                "statements libpg_query cannot parse alone (the corpus's own syntax errors)",
            ),
        ];
        let mut errors = Vec::new();
        for (what, name, found, about) in buckets {
            let path = listing_path(&name);
            if std::env::var("HACIVAT_DIFFERENTIAL_WRITE").as_deref() == Ok("1") {
                let header = format!(
                    "owner: Task 20 (generated by pg_regress_differential with \
                     HACIVAT_DIFFERENTIAL_WRITE=1).\nThe {TAG} regression corpus's {about}.\n\
                     file<TAB>start..end (bytes of our strict range)<TAB>FNV-1a 64 of its text; \
                     no corpus text is committed."
                );
                std::fs::create_dir_all(path.parent().unwrap()).unwrap();
                std::fs::write(&path, listing(&header, found)).unwrap();
                continue;
            }
            let listed = std::fs::read_to_string(&path)
                .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
            if let Err(e) = check_listing(found, &listed, TOLERANCE) {
                errors.push(format!("{what} ({}): {e}", path.display()));
            }
        }
        assert!(o.unreadable.len() <= 1, "unreadable: {:?}", o.unreadable);
        assert!(o.files >= 200, "{} files", o.files);
        assert!(o.agreed >= 10_000, "{} statements agree", o.agreed);
        assert!(
            o.per_mille() >= 999.0,
            "{:.2} per mille of the comparable agree (the P0 exit is 999)",
            o.per_mille()
        );
        assert!(errors.is_empty(), "{}", errors.join("\n"));
    }
}
